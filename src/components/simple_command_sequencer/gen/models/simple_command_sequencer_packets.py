from models.packets import packets, packet
from models.exceptions import ModelException
from util import model_loader
from util import redo

# Fetch the sizes used to compute the true frame-count bound, mirroring
# Num_Concurrent_Sequences_Type in simple_sequencer_types.ads
# (Packet_Buffer_Type'Length / Sequence_Frame_Summary.Size_In_Bytes). Results
# are cached at module level since they cannot change within a build.
_packet_buffer_size_bytes = [None]
_frame_summary_size_bytes = [None]


def _get_packet_buffer_size_bytes():
    if _packet_buffer_size_bytes[0] is None:
        packet_model = model_loader.try_load_model_by_name(
            "Packet", model_types="record"
        )
        if not packet_model:
            raise ModelException(
                "Could not load model for Packet.T. This must be in the path."
            )
        for fld in packet_model.fields.values():
            if fld.name == "Buffer":
                _packet_buffer_size_bytes[0] = int(fld.size / 8)
                break
        else:
            assert False, "No field 'Buffer' found in Packet.T type"
    return _packet_buffer_size_bytes[0]


def _get_frame_summary_size_bytes():
    if _frame_summary_size_bytes[0] is None:
        summary_model = model_loader.try_load_model_by_name(
            "Sequence_Frame_Summary", model_types="record"
        )
        if not summary_model:
            raise ModelException(
                "Could not load model for Sequence_Frame_Summary.T. This must "
                "be in the path."
            )
        _frame_summary_size_bytes[0] = int(summary_model.size / 8)
    return _frame_summary_size_bytes[0]


def get_max_frames_per_packet():
    """
    The largest number of Sequence_Frame_Summary records that fit in one
    packet buffer -- the Python mirror of Num_Concurrent_Sequences_Type'Last.
    This is derived from the project's actual configuration (the packet buffer
    size is set in the project configuration YAML), so it tracks configuration
    changes automatically. Used by the command_sequences model to validate a
    suite's num_concurrent_sequences at load time.
    """
    return _get_packet_buffer_size_bytes() // _get_frame_summary_size_bytes()


class simple_command_sequencer_packets(packets):
    """
    This model is a specialized packet suite for the simple command sequencer
    packets. This class inherits from the normal packets model but adds some
    extra functionality needed to the summary packet. In particular, the summary
    packet's type is derived from the Num_Concurrent_Sequences initialization
    parameter given to the component instance in the assembly model.
    """
    def submodel_name(self):
        """This is just a "decorated" packet object, so make sure everyone treats it like that."""
        return "packets"

    def set_assembly(self, assembly):
        # Set assembly:
        self.assembly = assembly

        # The summary packet contents are autogenerated based on the number of
        # concurrent sequences (frames) the suite this instance is initialized
        # with declares (num_concurrent_sequences in the command sequences
        # yaml). The FSW does not need this type to correctly populate the
        # packet, but ground tools and assembly documentation do. So, we
        # dynamically assign a type to this packet at assembly runtime: the
        # instance's Config init parameter names the generated suite package,
        # and the suite generates a matching <suite>_summary_record type
        # alongside its other outputs -- the frame pool and the packet layout
        # come from the same model value and can never disagree.
        for key, pkt in self.entities.items():
            # Find the packet we need to fill the type in for.
            if (
                pkt.suite.component.name == "Simple_Command_Sequencer"
                and pkt.name == "Summary_Packet"
            ):
                config_value = self.component.init.get_parameter_value("Config")
                suite_package = str(config_value).strip().split(".")[0] if config_value else ""
                if not suite_package:
                    raise ModelException(
                        "Simple_Command_Sequencer instance '"
                        + self.component.instance_name
                        + "' must be initialized with the Config constant of a "
                        + "generated command sequences suite package (e.g. "
                        + "'My_Suite_Command_Sequences.Config') to size its "
                        + "summary packet type, found: '"
                        + str(config_value) + "'."
                    )
                model_name = suite_package.lower() + "_summary_record"
                model_path = model_loader.get_model_file_path(
                    model_name, model_types=["record"]
                )
                if not model_path:
                    raise ModelException(
                        "Could not find Simple Command Sequencer packet type model file: '"
                        + model_name
                        + "'. It is generated from the command sequences suite '"
                        + suite_package + "'."
                    )

                # Make sure the model file has been autogenerated. Note that this causes a circular
                # dependency loop if shallow_load is not set to True in the generator
                # for the packet type.
                redo.redo_ifchange(model_path)

                # Now replace the packet by a new packet with the autogenerated type.
                self.entities[key] = packet(
                    name=pkt.name,
                    type=model_name + ".T",
                    description=pkt.description,
                    id=pkt.id,
                    suite=pkt.suite,
                )

                # Let's also add the type to our suite and component's complex types:
                self.type_models.append(self.entities[key].type_model)
                self.component.complex_types[
                    self.entities[key].type_model.name
                ] = self.entities[key].type_model

        # Call the base class version:
        super(simple_command_sequencer_packets, self).set_assembly(assembly)
